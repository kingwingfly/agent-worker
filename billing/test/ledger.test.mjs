const user = '12345', now = Date.UTC(2027, 0, 31, 12)
const usage = (input, output = 0, read = 0, write = 0) => ({
  input_tokens: input, output_tokens: output, cache_creation_input_tokens: write, cache_read_input_tokens: read
})
function database(t) {
  const db = new DatabaseSync(':memory:')
  t.after(() => db.close())
  return { exec(query, ...params) {
    const rows = db.prepare(query).all(...params)
    return { toArray: () => rows }
  } }
}
function setup(t, settings = {}) {
  const book = new Ledger(database(t))
  book.configure({ ...defaults, free_weekly_tokens: 100, ...settings })
  book.enroll(user, now)
  return book
}
const status = code => err => err.status === code
const gift = (book, tokens) => book.adjust(user, {action:'airdrop', tokens, reason:'Test', key:crypto.randomUUID()}, now)
const buyPlan = (book, at = now) => {
  const key = crypto.randomUUID()
  book.subscribe(user, key, plan(book.settings()).offer, at)
  return key
}
test('USD buys whole tokens, output rates support fractional ratios, and invalid dollar amounts are refused', () => {
  assert.equal(tokensForUsd(100, '1.00'),1_000_000)
  assert.equal(usageTokens(0,500_000,defaults),1_000_000)
  assert.equal(tokensForUsd(100,'3.00'),333_333)
  assert.equal(plan({...defaults,input_usd:'3.00',monthly_usd:'1.00'}).plan_price_tokens,333_333)
  const rates = {...defaults,input_usd:'1.50',output_usd:'2.00'}
  assert.equal(usageTokens(100,3,rates),104)
  assert.equal(usageTokens(0,1,rates),2)
  for (const amount of ['0','0.001','10000.01','1e2',-1]) assert.throws(()=>amountCents(amount),status(400))
  assert.throws(()=>settingsFrom({...defaults,output_usd:'0'}),status(400))
})
test('shared holds cap output at its selling rate, then settle actual and cached input at the quoted rates', t => {
  const book = setup(t, {input_cost:3, output_cost:12, cache_read_cost:1, cache_write_cost:4})
  const id = crypto.randomUUID()
  assert.deepEqual(book.reserve({user,id},now), {count_required:true})
  assert.deepEqual(book.reserve({user,id,input:20,output:200},now),{max_output:40})
  assert.throws(()=>book.access(user,now),status(429))
  book.configure({...book.settings(),input_cost:200,output_usd:'4.00'})
  book.settle({id,usage:usage(20,5,10,2)},now)
  book.settle({id,usage:usage(20,5,10,2)},now)
  const detail = book.detail(user,now)
  assert.equal(detail.remaining_weekly_tokens,58)
  assert.equal(detail.wallet_tokens,0)
  assert.equal(detail.billable_tokens,37)
  assert.equal(detail.cost_usd,(60+60+10+8)/1e6)
  assert.throws(()=>book.reserve({user,id:crypto.randomUUID(),input:55,output:1},now),status(402))
})
test('everyone gets one weekly window, a late refund cannot refill a new week, and there is no five-hour reset', t => {
  const book = setup(t,{free_weekly_tokens:10,output_usd:'1'})
  const id = crypto.randomUUID()
  book.reserve({user,id,input:2,output:8},now)
  book.settle({id,usage:usage(2,8)},now+1)
  assert.throws(()=>book.access(user,now+6*HOUR),status(402))
  book.enroll(user,now+WEEK)
  assert.equal(book.account(user,now+WEEK).remaining_weekly_tokens,10)
  const next=crypto.randomUUID()
  book.reserve({user,id:next,input:2,output:8},now+2*WEEK-100)
  const current=crypto.randomUUID()
  book.reserve({user,id:current,input:2,output:2},now+2*WEEK)
  book.settle({id:next,usage:usage(2)},now+2*WEEK+1)
  assert.equal(book.balance(user,now+2*WEEK+1),6)
  assert.equal(book.account(user,now+4*WEEK).remaining_weekly_tokens,10)
})
