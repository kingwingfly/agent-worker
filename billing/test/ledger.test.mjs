test('monthly renewals use the confirmed token price exactly once, and cancellation preserves the paid term', t => {
  const book=setup(t), feb=Date.UTC(2027,1,28,12), march=Date.UTC(2027,2,31,12)
  gift(book,2_000_000)
  const key=buyPlan(book)
  assert.equal(book.account(user,now).subscriptions[0].ends_at,feb)
  book.configure({...book.settings(),monthly_usd:'5.00'})
  book.renewDue(feb)
  book.renewDue(feb+1)
  const account=book.account(user,feb+1)
  assert.equal(account.subscriptions[0].ends_at,march)
  assert.equal(account.subscriptions[0].periods_paid,2)
  assert.equal(account.wallet_tokens,0)
  assert.throws(()=>book.cancel('321',key),status(404))
  book.cancel(user,key)
  book.cancel(user,key)
  assert.equal(book.account(user,march-1).tier,'subscriber')
  gift(book,5_000_000)
  assert.equal(book.account(user,march).tier,'free')
  assert.equal(book.account(user,march).wallet_tokens,5_000_000)
})
