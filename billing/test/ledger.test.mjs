  assert.equal(account.subscriptions.length,1)
  assert.equal(account.subscriptions[0].price_tokens,1_000_000)
  assert.equal(account.subscriptions[0].usd,'1.00')
  book.configure({...book.settings(),free_weekly_tokens:80})
  assert.equal(book.account(user,now+5*HOUR).remaining_weekly_tokens,360)
  assert.equal(book.account(user,now+WEEK).remaining_weekly_tokens,400)
