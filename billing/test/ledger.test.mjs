test('upgrading an existing ledger preserves wallets, in-flight usage, passes and unpaid invoices exactly once', t => {
  const sql=database(t)
  for (const statement of [
    'CREATE TABLE settings (id INTEGER PRIMARY KEY, body TEXT)',
    'CREATE TABLE users (id TEXT PRIMARY KEY,created_at INTEGER,bonus INTEGER,blocked INTEGER DEFAULT 0)',
    'CREATE TABLE subscriptions (id TEXT PRIMARY KEY,user TEXT,source TEXT,starts_at INTEGER,ends_at INTEGER,weekly INTEGER,window INTEGER,remaining INTEGER,revoked INTEGER DEFAULT 0)',
    'CREATE TABLE invoices (id TEXT PRIMARY KEY,user TEXT,chain TEXT,amount TEXT,recipient TEXT,reference TEXT,weekly INTEGER,weeks INTEGER,created_at INTEGER,expires_at INTEGER,status TEXT,tx TEXT,precheck TEXT,UNIQUE(chain,tx))',
    'CREATE TABLE topups (invoice TEXT PRIMARY KEY,packs INTEGER,credits INTEGER,usd_cents INTEGER,rate TEXT)',
    'CREATE TABLE calls (id TEXT PRIMARY KEY,user TEXT,created_at INTEGER,status TEXT,held INTEGER,allocation TEXT,ratio INTEGER,rates TEXT,tokens INTEGER DEFAULT 0,cost_usd REAL DEFAULT 0,charged INTEGER DEFAULT 0)',
    'CREATE TABLE adjustments (id TEXT PRIMARY KEY,user TEXT,action TEXT,reason TEXT,credits INTEGER,created_at INTEGER,request TEXT)'
  ]) sql.exec(statement)
  const old={tokens_per_credit:10,free_credits:0,stars_price:500,pack_usd:'10.00',input_cost:1,output_cost:2,cache_write_cost:0,cache_read_cost:0}
  sql.exec('INSERT INTO settings VALUES (1,?)',JSON.stringify(old))
  sql.exec('INSERT INTO users VALUES (?,?,?,0)',user,now,2_400_000)
  sql.exec("INSERT INTO subscriptions VALUES (?,?,'Admin',?,?,2000000,0,1500000,0)",crypto.randomUUID(),user,now,now+2*WEEK)
  const call=crypto.randomUUID(), topup=crypto.randomUUID(), legacyPass=crypto.randomUUID()
  sql.exec("INSERT INTO calls (id,user,created_at,status,held,allocation,ratio,rates) VALUES (?,?,?,'reserved',1000000,?,10,?)",
    call,user,now,JSON.stringify([{take:1_000_000}]),JSON.stringify(old))
  for (const [id,weekly] of [[topup,0],[legacyPass,3]]) {
    sql.exec("INSERT INTO invoices VALUES (?,?,'XTR','25','','',?,2,?,?,'open',NULL,NULL)",id,user,weekly,now,now+HOUR)
  }
  sql.exec('INSERT INTO topups VALUES (?,1,3,250,NULL)',topup)
  let book=new Ledger(sql)
  assert.equal(book.account(user,now).wallet_tokens,24)
  assert.equal(book.account(user,now).available_tokens,39)
  book=new Ledger(sql)
  assert.equal(book.account(user,now).wallet_tokens,24)
  assert.equal(book.order(topup,user).tokens,30)
  book.settle({id:call,usage:usage(2,2,50)},now)
  assert.equal(book.account(user,now).wallet_tokens,30)
  book.pay(topup,user,'old-topup',now)
  book.pay(topup,user,'old-topup',now)
  assert.equal(book.account(user,now).wallet_tokens,60)
  book.pay(legacyPass,user,'old-pass',now)
  assert.equal(book.account(user,now).available_tokens,105)
  assert.equal(book.showOrder(book.order(legacyPass,user),now).product,'legacy_plan')
  book.stars({user,kind:'refund',invoice:legacyPass,amount:25,currency:'XTR',charge:'old-pass'},now)
  assert.equal(book.account(user,now).available_tokens,75)
})
